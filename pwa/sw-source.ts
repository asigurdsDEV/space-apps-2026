// The service worker's source, generated at build time with the list of built files.
// Strategy: built files are content-hashed, so cache-first; the page (index.html) is
// network-first with a short timeout, so new deploys show at once but bad wifi falls back
// to the cached game. Other origins (PeerJS signalling) are never touched.

/** Seconds to wait for the network on a page load before using the cached page. */
export const PAGE_TIMEOUT_MS = 4000

export function serviceWorkerSource(assets: readonly string[], version: string): string {
  return `// Generated by pwa/plugin.ts at build time. Do not edit.
const CACHE = 'smdg-${version}'
const ASSETS = ${JSON.stringify(assets)}
const url = (path) => new URL(path, self.registration.scope).href
const STATIC = new Set(ASSETS.map(url))
const timeout = (ms) => new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms))

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS.map(url))).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('smdg-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return

  const page = request.mode === 'navigate'
  const manifest = request.url === url('game-assets.json')
  // Only build-listed static files belong in this cache; API credentials must stay on the network.
  if (!page && !STATIC.has(request.url)) return
  if (page || manifest) {
    const network = fetch(request)
    event.respondWith(
      Promise.race([network, timeout(${PAGE_TIMEOUT_MS})])
        .then((response) => {
          if (response.ok) {
            const copy = response.clone()
            caches.open(CACHE).then((cache) => cache.put(page ? url('index.html') : request, copy))
          }
          return response
        })
        .catch(() => caches.match(page ? url('index.html') : request, { ignoreVary: true }).then((cached) => cached || network)),
    )
    return
  }

  event.respondWith(
    // Preview/CDN Vary: Origin differs between fetch() and module imports; these exact static URLs
    // have the same public bytes for both. Keep the exception limited to the build's allowlist.
    caches.match(request, { ignoreVary: true }).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone()
            caches.open(CACHE).then((cache) => cache.put(request, copy))
          }
          return response
        }),
    ),
  )
})
`
}

/** Short, stable version string for a list of files (their names carry content hashes). */
export function versionOf(files: readonly string[]): string {
  let h = 5381
  for (const ch of files.join('\n')) h = ((h * 33) ^ ch.charCodeAt(0)) >>> 0
  return h.toString(36)
}
